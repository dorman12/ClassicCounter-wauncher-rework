using System;
using System.IO;
using System.Text;
using Wauncher.Utils;

namespace Wauncher.Services
{
    public static class AutoConfigService
    {
        public const string ConfigFileName = "wauncher_autoexec.cfg";

        public static string GetDefaultCommands()
        {
            return """
// ClassicCounter Wauncher Auto-Config
// Prevents viewmodel, crosshair, and bind resets

// ── Viewmodel & Field of View ──
viewmodel_fov 68
viewmodel_offset_x 2.5
viewmodel_offset_y 0
viewmodel_offset_z -1.5
viewmodel_presetpos 3
cl_viewmodel_shift_left_amt 0.5
cl_viewmodel_shift_right_amt 0.25
cl_bob_lower_amt 5
cl_bobamt_lat 0.1
cl_bobamt_vert 0.1
cl_righthand 1

// ── Competitive Network Rates (128 Tick) ──
rate 786432
cl_cmdrate 128
cl_updaterate 128
cl_interp 0
cl_interp_ratio 1

// ── Convenience & FPS ──
bind "mwheeldown" "+jump"
r_drawtracers_firstperson 1
cl_autowepswitch 0
fps_max 0

// ── Lock Settings into config.cfg ──
host_writeconfig
""";
        }

        public static string GetConfigPath()
        {
            string gameDir = GamePathService.GetGameDirectory();
            return Path.Combine(gameDir, "csgo", "cfg", ConfigFileName);
        }

        public static string LoadSavedOrExistingCommands(string fallbackCommands)
        {
            try
            {
                string path = GetConfigPath();
                if (File.Exists(path))
                {
                    string content = File.ReadAllText(path, Encoding.UTF8);
                    if (!string.IsNullOrWhiteSpace(content))
                        return content;
                }
            }
            catch { }

            return !string.IsNullOrWhiteSpace(fallbackCommands) ? fallbackCommands : GetDefaultCommands();
        }

        public static bool SaveAndApply(string commands, bool enabled)
        {
            try
            {
                string gameDir = GamePathService.GetGameDirectory();
                string cfgDir = Path.Combine(gameDir, "csgo", "cfg");
                Directory.CreateDirectory(cfgDir);

                string path = Path.Combine(cfgDir, ConfigFileName);

                if (string.IsNullOrWhiteSpace(commands))
                    commands = GetDefaultCommands();

                // Ensure host_writeconfig is present at the end
                if (!commands.Contains("host_writeconfig", StringComparison.OrdinalIgnoreCase))
                {
                    commands = commands.TrimEnd() + "\n\nhost_writeconfig\n";
                }

                File.WriteAllText(path, commands, Encoding.UTF8);

                // Also ensure csgo/cfg/autoexec.cfg references it as a backup
                try
                {
                    string autoexecPath = Path.Combine(cfgDir, "autoexec.cfg");
                    string execLine = $"exec {ConfigFileName}";
                    if (File.Exists(autoexecPath))
                    {
                        string existing = File.ReadAllText(autoexecPath, Encoding.UTF8);
                        if (!existing.Contains(ConfigFileName, StringComparison.OrdinalIgnoreCase))
                        {
                            File.AppendAllText(autoexecPath, $"\n{execLine}\n", Encoding.UTF8);
                        }
                    }
                    else
                    {
                        File.WriteAllText(autoexecPath, $"// Auto-generated by Wauncher\n{execLine}\nhost_writeconfig\n", Encoding.UTF8);
                    }
                }
                catch { }

                Terminal.Print($"[AutoConfig] Saved and applied to {path}");
                return true;
            }
            catch (Exception ex)
            {
                Terminal.Error($"[AutoConfig] Failed to save config: {ex.Message}");
                return false;
            }
        }
    }
}
